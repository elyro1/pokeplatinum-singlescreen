#!/usr/bin/env python3
"""Writes src/port/bw_icon_palettes.inc, BW2's table of which of the three icon palettes each icon uses.

The table is in BW2's ARM9 (read by PokeIcon_GetPalette, 0x02021034 in US Black 2), not in an archive, so the
game can't get it from the archives it extracts. It holds palette numbers only, no art. Run once by hand with a
US Black 2 ROM: import_bw_icon_palettes.py <rom.nds> <output.inc>
"""
import struct
import sys

ARM9_TABLE_ADDRESS = 0x0209054C
# 8 files, then two for each entry, in the 1510 files of the icon archive
ENTRY_COUNT = (1510 - 8) // 2


def decompress_arm9(image):
    """Undoes the backward LZ compression that ARM9 binaries end in."""
    footer, extra = struct.unpack_from("<II", image, len(image) - 8)
    compressed_size = footer & 0xFFFFFF
    header_size = footer >> 24
    out = bytearray(image) + bytearray(extra)
    src = len(image) - header_size
    dst = len(out)
    end = len(image) - compressed_size
    while src > end:
        src -= 1
        flags = image[src]
        for _ in range(8):
            if src <= end:
                break
            if flags & 0x80:
                src -= 2
                pair = image[src + 1] << 8 | image[src]
                count = (pair >> 12) + 3
                distance = (pair & 0xFFF) + 3
                for _ in range(count):
                    dst -= 1
                    out[dst] = out[dst + distance]
            else:
                src -= 1
                dst -= 1
                out[dst] = image[src]
            flags <<= 1
    return bytes(out)


def main():
    rom = open(sys.argv[1], "rb").read()
    if rom[0x0C:0x0F] not in (b"IRE", b"IRD"):
        sys.exit("Not a Black 2 or White 2 ROM")
    offset, _, ram, size = struct.unpack_from("<IIII", rom, 0x20)
    arm9 = decompress_arm9(rom[offset : offset + size])
    start = ARM9_TABLE_ADDRESS - ram
    # Low nibble: the palette; high nibble: the female icon's, which no Platinum species has
    table = [byte & 0xF for byte in arm9[start : start + ENTRY_COUNT]]
    if max(table) > 2:
        sys.exit("The table has a palette past the third; wrong ROM or address")
    with open(sys.argv[2], "w") as out:
        out.write("// Generated by tools/scripts/import_bw_icon_palettes.py. Palette numbers only, no art\n")
        for i in range(0, len(table), 32):
            out.write(" ".join(f"{value}," for value in table[i : i + 32]) + "\n")


if __name__ == "__main__":
    main()
