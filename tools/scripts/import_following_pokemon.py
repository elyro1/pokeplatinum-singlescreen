#!/usr/bin/env python3
"""Import HG/SS overworld metadata and mappings without copying texture assets.

Usage: python3 tools/scripts/import_following_pokemon.py /path/to/pokeheartgold
Normal builds use the generated metadata; desktop graphics come from the user's HG/SS ROM extraction.
"""
import argparse
import csv
import hashlib
import json
from pathlib import Path
import re
import struct

ROOT = Path(__file__).resolve().parents[2]
DEST = ROOT / 'res/graphics/following_pokemon'


def array(source, name):
    body = re.search(r'\b' + name + r'\[\]\s*=\s*\{(.*?)\};', source, re.S).group(1)
    return [x.strip() for x in re.sub(r'//[^\n]*', '', body).split(',') if x.strip()]


def texture_info(data):
    if data[:4] != b'BTX0' or struct.unpack_from('<I', data, 8)[0] != len(data):
        raise ValueError('Invalid NSBTX')
    tex = struct.unpack_from('<I', data, 16)[0]
    tex_dict = tex + struct.unpack_from('<H', data, tex + 14)[0]
    palette_dict = tex + struct.unpack_from('<H', data, tex + 52)[0]
    if data[tex_dict + 1] != 8 or data[palette_dict + 1] != 2:
        raise ValueError('Expected eight directional frames and normal/shiny palettes')
    entry = tex_dict + struct.unpack_from('<H', data, tex_dict + 6)[0] + 4
    sizes = []
    for i in range(8):
        value = struct.unpack_from('<I', data, entry + i * 8)[0]
        sizes.append((8 << ((value >> 20) & 7), 8 << ((value >> 23) & 7)))
    if len(set(sizes)) != 1 or sizes[0] not in ((32, 32), (64, 64)):
        raise ValueError(f'Unexpected texture dimensions: {sizes}')
    return sizes[0][0]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('heartgold', type=Path)
    args = parser.parse_args()
    source = (args.heartgold / 'src/follow_mon.c').read_text()
    constants = dict((name, int(value)) for name, value in re.findall(
        r'^#define\s+(FOLLOWER_MON_\w+)\s+(\d+)',
        (args.heartgold / 'include/constants/follow_mon_idx.h').read_text(), re.M))
    indices = [constants[x] for x in array(source, 'sModelIndexLUT')]
    forms = [int(x) for x in array(source, 'sFormMaxLUT')]
    females = [x == 'TRUE' for x in array(source, 'sFemaleFlagLUT')]
    assert len(indices) == 494 and len(forms) == len(females) == 493
    params = list(csv.DictReader((args.heartgold / 'files/fielddata/tsurepoke/tp_param.csv').open()))
    assert len(params) == 566
    assets, texture_bytes = [], 0
    for index, param in enumerate(params):
        member = 297 + index
        data = (args.heartgold / f'files/data/mmodel/mmodel/mmodel_{member:08}.NSBTX').read_bytes()
        size = texture_info(data)
        assets.append(dict(index=index, name=param['index'].removeprefix('TSURE_POKE_'),
                           source_member=member, offset=texture_bytes, length=len(data), size=size,
                           hover=param['hover'] == 'true', too_tall=param['too_tall'] == 'true',
                           alternate_bob=param['unk2_0'] == 'true',
                           sha256=hashlib.sha256(data).hexdigest()))
        texture_bytes += len(data)
    species = [dict(species=i, base=indices[i], max_form=forms[i - 1], female=females[i - 1])
               for i in range(1, 494)]
    for mon in species:
        assert mon['base'] + max(mon['max_form'], int(mon['female'])) < len(assets)
    DEST.mkdir(parents=True, exist_ok=True)
    (DEST / 'manifest.json').write_text(json.dumps(dict(format=1, assets=assets, species=species), indent=2) + '\n')
    (DEST / 'graphics.inc').write_text('// Generated by import_following_pokemon.py. Define POKEMON_GRAPHIC before including.\n' +
        ''.join(f'POKEMON_GRAPHIC({x["index"]}, BILLBOARD_MODEL_GENERIC_{x["size"]}x{x["size"]}, '
                f'{"TRACK_TYPE_NONE" if x["hover"] else "TRACK_TYPE_FOOTSTEPS"}) // {x["name"]}\n' for x in assets))
    # Expose names to map JSON and scripts through the existing enum pipeline.
    constants_path = ROOT / 'generated/object_events_gfx.txt'
    begin = '# BEGIN HGSS OVERWORLD POKEMON (import_following_pokemon.py)'
    end = '# END HGSS OVERWORLD POKEMON'
    existing = re.sub(re.escape(begin) + r'.*?' + re.escape(end) + r'\n', '', constants_path.read_text(), flags=re.S)
    block = begin + '\n'
    for asset in assets:
        for shiny, suffix in [(0, ''), (1, '_SHINY')]:
            block += f'OBJ_EVENT_GFX_MON_{asset["name"]}{suffix} = {0x4000 + asset["index"] * 2 + shiny}\n'
    block += end + '\n'
    constants_path.write_text(existing.replace('OBJ_EVENT_GFX_SENTINEL_ID = 65535', block + 'OBJ_EVENT_GFX_SENTINEL_ID = 65535'))
    print(f'Imported {len(species)} species, {len(assets)} variants, {texture_bytes} texture bytes indexed (no graphics copied)')


if __name__ == '__main__':
    main()
