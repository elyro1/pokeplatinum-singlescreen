#!/usr/bin/env python3
"""Import checked HG reactions with explicit Sinnoh context pools (no HG map/flag/tile IDs)."""
import argparse
import hashlib
import json
from pathlib import Path
import struct
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[2]
DEST = ROOT / 'res/graphics/following_pokemon'
# General, ordinary towns, routes, caves, forests, snowy places. Location-specific
# conditions are excluded below; these are thematic pools, not Johto map aliases.
POOLS = [None, 127, 177, 210, 214, 203]
FIELDS = ['hp', 'mood', 'friend', 'nature', 'gender', 'status', 'item', 'type',
          'grass', 'species', 'weather', 'facing', 'npcs', 'time', 'hidden', 'case', 'chance']


def members(data):
    assert data[:4] == b'NARC'
    off = struct.unpack_from('<H', data, 12)[0]
    assert data[off:off+4] == b'BTAF'
    count = struct.unpack_from('<H', data, off+8)[0]
    fat = [struct.unpack_from('<II', data, off+12+i*8) for i in range(count)]
    off += struct.unpack_from('<I', data, off+4)[0]
    assert data[off:off+4] == b'BTNF'
    off += struct.unpack_from('<I', data, off+4)[0]
    assert data[off:off+4] == b'GMIF'
    return [data[off+8+s:off+8+e] for s, e in fat]


def decode_rule(b):
    flags, misc, map_id, tile, flag = (struct.unpack_from('<H', b, x)[0] for x in [8, 10, 12, 14, 18])
    if map_id or tile or b[7] or b[4] >> 5 or b[16] & 0x1E or flag not in (0, 332):
        return None
    return dict(hp=b[0], mood=b[1]&15, friend=b[1]>>4, nature=b[2]&7,
                gender=(b[2]>>3)&3, status=b[2]>>5, item=b[3]&31, type=b[4]&31,
                grass=b[5], species=b[6], weather=flags&7, facing=flags>>13,
                npcs=misc&7, time=(misc>>3)&7, hidden=b[16]>>5,
                case=int(flag == 332), chance=b[17], action=misc>>6)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('heartgold', type=Path)
    args = parser.parse_args()
    sources = {}
    def read(path):
        data = (args.heartgold/path).read_bytes()
        sources[path] = hashlib.sha256(data).hexdigest()
        return data
    conds = members(read('files/a/2/2/0'))
    actions = members(read('files/a/2/2/1'))
    anims = members(read('files/a/2/2/2'))
    assert len(actions) == 1023 and all(len(a) == 52 for a in actions)
    assert len(anims) == 108 and all(len(a) == 80 for a in anims)
    decoded = []
    for a in actions:
        steps = []
        for off in range(0, 40, 8):
            anim, msg, sound, emote, wait = struct.unpack_from('<HHHBB', a, off)
            if anim == 65535:
                break
            assert anim <= len(anims) and msg <= 759 and emote <= 14
            assert sound in (0, 2379, 2380)
            steps.append((anim, msg, sound, emote, wait))
        question, yes, no, friend, mood, gift, leaf = struct.unpack_from('<IHHbbBB', a, 40)
        assert yes <= len(actions) and no <= len(actions) and gift <= 100
        decoded.append((steps, question, yes, no, friend, mood, gift, leaf))
    def supported(action, seen=frozenset()):
        if action == 0:
            return True
        if action in seen:
            return False
        a = decoded[action-1]
        return not a[7] and all(supported(n, seen | {action}) for n in a[2:4])
    lines = ['// Generated by import_follower_reactions.py; HG IDs are one-based.\n',
             'static const FollowingPokemonReaction sReactions[] = {\n    {0},\n']
    for action_id, (steps, question, yes, no, friend, mood, gift, leaf) in enumerate(decoded, 1):
        padded = steps + [(0,0,0,0,0)] * (5-len(steps))
        lines.append('    { { ' + ', '.join('{'+','.join(map(str, s))+'}' for s in padded)
                     + f' }}, {len(steps)}, {int(bool(question))}, {yes}, {no}, {friend}, {mood}, {gift}, {int(supported(action_id))}' + ' },\n')
    lines.append('};\nstatic const FollowingPokemonReactionFrame sReactionAnimations[][10] = {\n    {{255,0,0,0,0,0}},\n')
    for anim in anims:
        frames = [struct.unpack_from('<BBbbbB', anim, off) for off in range(0,80,8)]
        assert all(f[0] in (0,1,2,3,4,255) for f in frames)
        lines.append('    { '+', '.join('{'+','.join(map(str,f))+'}' for f in frames)+' },\n')
    lines.append('};\nstatic const ReactionRule sReactionRules[] = {\n')
    for pool, section in enumerate(POOLS):
        raw = conds[0 if section is None else section+1]
        for off in range(0,len(raw),20):
            r = decode_rule(raw[off:off+20])
            if r and r['action'] and supported(r['action']):
                lines.append('    { '+f'{pool}, {off//20}, {r["action"]}, '+', '.join(str(r[f]) for f in FIELDS)+' },\n')
    lines.append('};\n')
    # Keep the established context selector as a guaranteed health/weather fallback,
    # but use HG's actual matching animation/emote action instead of a bare message.
    lines.append('static const u16 sMessageReactions[759] = {\n')
    for msg in range(1,760):
        match = next((i for i,a in enumerate(decoded,1) if supported(i) and not a[1] and not a[6]
                      and len(a[0]) == 1 and a[0][0][1] == msg), 0)
        if match:
            lines.append(f'    [{msg-1}] = {match},\n')
    lines.append('};\n')
    categories = members(read('files/a/2/3/1'))[0]
    assert len(categories) >= 493
    lines.append('static const u8 sReactionSpecies[] = { 0, '+','.join(map(str,categories[:493]))+' };\n')
    (DEST/'reactions.inc').write_text(''.join(lines))
    messages = []
    data = read('files/msgdata/msg/msg_0265.gmm')
    rows = ET.fromstring(data).findall('row')
    for i,row in enumerate(rows):
        assert int(row.attrib['index']) == i
        text = row.find("language[@name='English']").text or ''
        text = text.replace('\\n','\n').replace('\\r','\r').replace('\\f','\f')
        messages.append(dict(id=f'FollowingPokemon_Text_{i}', en_US=text.splitlines(keepends=True)))
    assert len(messages) == 759
    for index, name in [(32,'AccessoryStored'), (95,'AccessoryFull')]:
        row = next(r for r in ET.fromstring(read('files/msgdata/msg/msg_0040.gmm')).findall('row') if int(r.attrib['index']) == index)
        text = row.find("language[@name='English']").text
        text = text.replace('\\n','\n').replace('\\r','\r').replace('\\f','\f')
        messages.append(dict(id=f'FollowingPokemon_Text_{name}', en_US=text.splitlines(keepends=True)))
    (ROOT/'res/text/following_pokemon.json').write_text(json.dumps(dict(key=265,messages=messages),indent=2)+'\n')
    effects = members(read('files/a/1/0/3'))
    lines = ['// Generated by import_follower_reactions.py; private emote resources.\n']
    for member,name in [(130,'Model'),(150,'Sequence')]+[(i+2,f'Texture{i}') for i in range(14)]:
        blob = effects[member]
        assert len(blob)%4 == 0
        words = struct.unpack('<'+'I'*(len(blob)//4),blob)
        lines.append(f'static const u32 sReactionEmote{name}[] = {{\n')
        lines.extend('    '+','.join(f'0x{x:08x}' for x in words[i:i+12])+',\n' for i in range(0,len(words),12))
        lines.append('};\n')
    lines.append('static const struct { const void *data; u32 size; } sReactionEmoteTextures[] = {\n')
    lines.extend(f'    {{ sReactionEmoteTexture{i}, sizeof(sReactionEmoteTexture{i}) }},\n' for i in range(14))
    lines.append('};\n')
    (DEST/'reaction_emotes.inc').write_text(''.join(lines))
    generated = ['reactions.inc','reaction_emotes.inc']
    (DEST/'reactions_manifest.json').write_text(json.dumps(dict(format=1,sources=sources,
        generated={p:hashlib.sha256((DEST/p).read_bytes()).hexdigest() for p in generated},
        text_sha256=hashlib.sha256((ROOT/'res/text/following_pokemon.json').read_bytes()).hexdigest(),
        actions=len(actions),animations=len(anims),messages=len(messages),pools=POOLS),indent=2)+'\n')
    print('Imported 1023 reactions, 108 animations, 14 emotes and 761 messages')


if __name__ == '__main__':
    main()
