#!/usr/bin/env python3
"""Generate Pokémon texture metadata and species mappings from the manifest."""
import json
from pathlib import Path
import sys

manifest, output = map(Path, sys.argv[1:])
info = json.loads(manifest.read_text())
with output.open('w') as out:
    out.write('// Generated by embed_following_pokemon.py; do not edit.\n')
    out.write('static const PokemonTextureEntry sPokemonTextures[] = {\n')
    for a in info['assets']:
        out.write(f'    {{{a["offset"]}, {a["length"]}, {"TRUE" if a["alternate_bob"] else "FALSE"}, {"TRUE" if a["size"] == 64 else "FALSE"}}},\n')
    out.write('};\nstatic const PokemonSpeciesEntry sPokemonSpecies[] = {\n    {0, 0, FALSE},\n')
    for mon in info['species']:
        out.write(f'    {{{mon["base"]}, {mon["max_form"]}, {"TRUE" if mon["female"] else "FALSE"}}},\n')
    out.write('};\n')
