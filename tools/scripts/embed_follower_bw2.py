#!/usr/bin/env python3
"""Generate the BW2 follower conversion data from bw2_sprites.json.

Emits each variant's BW2 key and HG/SS shiny palette, and the NSBTX header that
port/follower_assets.cpp puts before eight frames and the normal/shiny palettes.
The header matches HG/SS's layout, so the converted files keep the manifest's sizes.
"""
import json
from pathlib import Path
import struct
import sys

FRAMES = 8
PALETTES = 2


def bit(name, index):
    return (name[index // 8] >> (index % 8)) & 1


def patricia(names):
    """NNS's dictionary tree, as nitrobtx's resource_tree.c builds it. Returns (refBit, left, right, entry) rows."""
    names = [n.ljust(16, b'\0') for n in names]
    ZERO = None

    def diff(a, b, start, stop):
        for i in range(start, stop - 1, -1):
            if (0 if a is ZERO else bit(names[a], i)) != (0 if b is ZERO else bit(names[b], i)):
                return i
        return -1

    # Nodes: [isLeaf, bit, entry, left, right]
    root = [True, 0, ZERO, None, None]
    holder = [root]
    for e in range(len(names)):
        ref, slot, current = 127, 0, holder
        while True:
            node = current[slot]
            stop = 0 if node[0] else node[1] + 1
            d = diff(e, node[2], ref, stop)
            if d < 0 and node[0]:
                raise ValueError('duplicate name')
            if d < 0:
                ref = node[1]
                current, slot = node, 4 if bit(names[e], node[1]) else 3
                continue
            leaf = [True, 0, e, None, None]
            current[slot] = [False, d, e, node, leaf] if bit(names[e], d) else [False, d, e, leaf, node]
            break
    order, stack, index_of, position = [], [holder[0]], {}, {}
    while stack:
        node = stack.pop()
        order.append(node)
        index_of[node[2]] = position[id(node)] = len(order)
        for child in (node[4], node[3]):
            if not child[0]:
                stack.append(child)
    rows = [(127, 1, 0, 0)]
    for node in order:
        def child(c):
            if c[0]:
                return 0 if c[2] is ZERO else index_of[c[2]]
            return position[id(c)]
        rows.append((node[1], child(node[3]), child(node[4]), node[2]))
    return rows


def lookup(rows, names, name):
    """NNS_G3dGetResDictIdxByName, to check the tree."""
    name = name.ljust(16, b'\0')
    prev, node = 127, rows[rows[0][1]]
    while node[0] < prev:
        prev = node[0]
        node = rows[node[2] if bit(name, node[0]) else node[1]]
    return node[3] if names[node[3]].ljust(16, b'\0') == name else -1


def dictionary(names, unit, data):
    rows = patricia(names)
    for i, n in enumerate(names):
        assert lookup(rows, names, n) == i
    tree = b''.join(struct.pack('<4B', *r) for r in rows)
    entry_offset = 8 + len(tree)
    body = struct.pack('<HH', unit, 4 + unit * len(names)) + b''.join(data) + b''.join(n.ljust(16, b'\0') for n in names)
    size = entry_offset + len(body)
    return struct.pack('<BBHHH', 0, len(names), size, 8, entry_offset) + tree + body


def header(size):
    frame_bytes = size * size // 2
    log = {32: 2, 64: 3}[size]
    # 4bpp, colour 0 transparent, as HG/SS's: S and T size, format 3, bit 29
    image = (log << 20) | (log << 23) | (3 << 26) | (1 << 29)
    extra = 0x80000000 | (size << 11) | size
    texs = dictionary([b'poke.%d' % i for i in range(FRAMES)], 8,
                      [struct.pack('<II', image | (i * frame_bytes >> 3), extra) for i in range(FRAMES)])
    pals = dictionary([b'poke_normal', b'poke_shiny'], 4, [struct.pack('<HH', i * 4, 0) for i in range(PALETTES)])
    tex_dict = 0x3C
    pal_dict = tex_dict + len(texs)
    tex_data = pal_dict + len(pals)
    pal_data = tex_data + FRAMES * frame_bytes
    block = pal_data + PALETTES * 32
    tex0 = struct.pack('<4sI', b'TEX0', block)
    tex0 += struct.pack('<IHHHHI', 0, FRAMES * frame_bytes >> 3, tex_dict, 0, 0, tex_data)
    tex0 += struct.pack('<IHHHHII', 0, 0, tex_dict, 0, 0, pal_data, pal_data)
    tex0 += struct.pack('<IHHHHI', 0, PALETTES * 32 >> 3, 0, pal_dict, 0, pal_data)
    assert len(tex0) == 0x3C
    tex0 += texs + pals
    out = struct.pack('<4sHHIHHI', b'BTX0', 0xFEFF, 1, 0x14 + block, 0x10, 1, 0x14) + tex0
    return out, 0x14 + block


def array(name, data):
    lines = [', '.join(f'0x{b:02x}' for b in data[i:i + 16]) for i in range(0, len(data), 16)]
    return f'static const unsigned char {name}[] = {{\n    ' + ',\n    '.join(lines) + '\n};\n'


def main():
    source, output = map(Path, sys.argv[1:])
    sprites = json.loads(source.read_text())['sprites']
    with output.open('w') as out:
        out.write('// Generated by embed_follower_bw2.py; do not edit.\n')
        for size in (32, 64):
            data, total = header(size)
            out.write(array(f'sTextureHeader{size}', data))
            out.write(f'#define TEXTURE_FILE_SIZE_{size} {total}\n')
        out.write('static const FollowerBw2Sprite sBw2Sprites[] = {\n')
        for i, s in enumerate(sprites):
            assert s['index'] == i
            colours = ', '.join('0x' + c for c in s['shiny'].split())
            out.write(f'    {{ {s["species"]}, {s["sex"]}, {s["form"]}, {{ {colours} }} }}, // {s["name"]}\n')
        out.write('};\n')


if __name__ == '__main__':
    main()
