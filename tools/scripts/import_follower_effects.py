#!/usr/bin/env python3
"""Import the HG/SS follower ball, burst model and burst texture animation."""
from pathlib import Path
import hashlib
import struct
import sys

ROOT = Path(__file__).resolve().parents[2]
source = Path(sys.argv[1]) / 'files/a/1/0/3'
data = source.read_bytes()
assert data[:4] == b'NARC'
fat = data.index(b'BTAF')
image = data.index(b'GMIF') + 8
lines = ['// Generated by import_follower_effects.py from HG/SS a/1/0/3.\n']
for member, name in [(0x81, 'Ball'), (0x68, 'Burst'), (0xA4, 'BurstAnim')]:
    start, end = struct.unpack_from('<II', data, fat + 12 + 8 * member)
    asset = data[image + start:image + end]
    assert asset[:4] in (b'BMD0', b'BTA0') and len(asset) % 4 == 0
    lines.append(f'// Member {member}, SHA256 {hashlib.sha256(asset).hexdigest()}\n')
    lines.append(f'static const u32 sFollower{name}[] = {{\n')
    words = struct.unpack('<' + str(len(asset) // 4) + 'I', asset)
    for i in range(0, len(words), 10):
        lines.append('    ' + ', '.join(f'0x{x:08x}' for x in words[i:i + 10]) + ',\n')
    lines.append('};\n')
(ROOT / 'res/graphics/following_pokemon/ball_effects.inc').write_text(''.join(lines))
